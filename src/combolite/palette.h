/* Четыре цвета «Вектора» под экран терминала: подбор по CIEDE2000.
 *
 * ЗАЧЕМ. У «Вектора» в 80 колонках (режим 512) четыре цвета на весь экран, а
 * BBS рисуют шестнадцатью цветами ANSI. Постоянное сведение (чёрный, тёмный,
 * серый, белый) сливает красный с зелёным и синим. Здесь цвета подбираются под
 * то, что сейчас на экране: из 256 цветов «Вектора» -- четыре, и каждый из 16
 * цветов ANSI -- в ближайший из них.
 *
 * ЦВЕТ «ВЕКТОРА» -- байт BBGGGRRR. Уровни: R и G -- шаг 36 (0..252), у синего
 * младшего разряда нет -- 0, 72, 144, 216 (разбор в goblins/palette/REPORT.md
 * проекта CO). Расстояние -- CIEDE2000 в Lab (D65, sRGB): на евклиде в RGB
 * серо-голубой уезжает в зелёный.
 *
 * ПОДБОР. Кандидаты -- ближайший цвет «Вектора» к каждому цвету ANSI, который
 * есть на экране, и чёрный. Перебор всех четвёрок: цена -- сумма ΔE00 с весом
 * цвета плюс штраф за пару «буква на фоне», которая слилась в один цвет (текст
 * пропал бы). Ячейка 0 -- всегда цвет ANSI 0: очищенная видеопамять машины и
 * пустые строки после прокрутки -- это ячейка 0, и они должны совпасть с фоном. */
#ifndef COMBO_PALETTE_H
#define COMBO_PALETTE_H

#include <stdint.h>

/* Что на экране: вес каждого цвета ANSI и сколько непустых ячеек с парой
 * (буква, фон). */
typedef struct {
    uint32_t w[16];
    uint16_t pair[16][16];
} pal_stats_t;

/* Подбор: цвета «Вектора» в col[4] и сведение ANSI -> 0..3 в map[16]. Цена --
 * в возврате (меньше -- лучше). */
double pal_choose(const pal_stats_t *st, uint8_t col[4], uint8_t map[16]);

/* Цена уже выбранных цветов на этой статистике. */
double pal_cost(const pal_stats_t *st, const uint8_t col[4], const uint8_t map[16]);

/* ΔE00 между двумя цветами «Вектора» и между цветом ANSI и цветом «Вектора». */
double pal_de_vec(uint8_t a, uint8_t b);
double pal_de_ansi(int ansi, uint8_t vec);

/* Ближайший цвет «Вектора» к цвету ANSI. */
uint8_t pal_nearest(int ansi);

/* CIEDE2000 по Lab -- для проверки по таблице Шармы. */
double pal_de2000(const double lab1[3], const double lab2[3]);

#endif
