/* Терминал на ESP: поток от модема (ANSI, CP437/CP866/UTF-8) -> экран 80x25.
 *
 * ЗАЧЕМ НА ESP. Консоль МикроДОС не знает ни ANSI, ни псевдографики ПК, а у
 * «Вектора» в 80 колонках четыре цвета на экран. Разбирать всё это на 8080
 * долго и тесно. ESP держит полный экран с цветом каждой ячейки, а «Вектору»
 * отдаёт только изменившиеся ячейки уже в его шрифте (vt_diff). Программа на
 * машине рисует и не знает про ANSI вовсе.
 *
 * ШРИФТ «ВЕКТОРА» -- в раскладке CP866: кириллица и та же псевдографика, что
 * у CP437 в B0h..DFh. CP437 переводится в неё почти один в один (буквы с
 * надстрочными знаками -- в латинские без них), CP866 идёт как есть, UTF-8
 * раскладывается по таблице. Что не нашлось -- «?».
 *
 * ЯЧЕЙКА -- символ шрифта и цвет: младшая тетрада -- буква, старшая -- фон,
 * номера 16 цветов ANSI (8..15 -- яркие). К четырём цветам «Вектора» их
 * сводит уже получатель разницы.
 *
 * ОТВЕТЫ ТЕРМИНАЛА (запрос позиции курсора ESC[6n и прочие) уходят обратно в
 * сеть через vt_reply_fn -- на плате это modem_put. */
#ifndef COMBO_VT_H
#define COMBO_VT_H

#include <stdint.h>

#define VT_COLS 80
#define VT_ROWS 25

#define VT_CP437 0
#define VT_CP866 1
#define VT_UTF8  2

typedef struct { uint8_t ch, at; } vt_cell_t;

void vt_init(int charset);
void vt_charset(int charset);
void vt_put(uint8_t b);                 /* байт из сети */
void vt_set_reply(void (*fn)(uint8_t)); /* куда слать ответы терминала */

const vt_cell_t *vt_cell(int row, int col);
int  vt_cur_row(void);
int  vt_cur_col(void);

/* РАЗНИЦА ДЛЯ «ВЕКТОРА». Сравнивает экран с тем, что у машины уже есть
 * (своя тень), и пишет в out не больше max байт команд:
 *   01 r c n at ch[n]   n ячеек одного цвета с колонки c строки r
 *   02 n                прокрутка вверх на n строк, снизу пустые (цвет 07)
 *   03 r c              курсор
 *   04 c0 c1 c2 c3      палитра (её вставляет term.c, не vt_diff)
 * Возвращает число байт; 0 -- машине нечего сообщать. Команда целиком
 * помещается в max или не пишется вовсе; тень меняется только на то, что
 * записано, так что прерванный обмен продолжается со следующего вызова. */
int  vt_diff(uint8_t *out, int max);
/* Забыть, что у машины на экране: следующая разница перерисует всё. */
void vt_resync(void);
/* У машины чистый экран (пробелы цвета 07, курсор неизвестен): так TERM.COM
 * входит -- он сам очищает видеопамять. Следующая разница -- только непустое. */
void vt_resync_blank(void);
/* Переслать ячейки, которые у машины теперь выглядят иначе (сменилось
 * сведение цветов): changed(ch, at) по тени -- 1, и ячейка уйдёт заново. */
void vt_invalidate(int (*changed)(uint8_t ch, uint8_t at));

#endif
