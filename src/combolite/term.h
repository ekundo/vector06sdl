/* Терминал «Вектора» в сеть: модем (modem.c) + экран (vt.c) за каналом.
 *
 * TERM.COM на «Векторе» ходит по кругу: шлёт кадр с нажатыми клавишами
 * (vchan.h, VOP_TERM_IO) и получает в ответ кусок разницы экрана. ESP
 * отвечает только на запрос, так что машина сама решает, сколько успевает
 * нарисовать, и поток не переполняет её очередь.
 *
 * КЛАВИШИ С «ВЕКТОРА»:
 *   20h..7Eh       символ ASCII как есть (ВК -- 0Dh, ЗБ -- 08h, ТАБ -- 09h,
 *                  АР2 -- 1Bh, УС+буква -- 01h..1Ah);
 *   80h..AFh, E0h..F1h  русские буквы в CP866 -- в сеть уходят в кодировке
 *                  BBS (CP866 как есть, UTF-8 двумя байтами, CP437 -- «?»);
 *   F8h..FFh       служебные: TK_* ниже, уходят последовательностями ANSI.
 *
 * Модем и экран крутит term_pump: байты из сети -- в экран, ответы экрана --
 * в сеть. На плате -- своя задача (term_esp.c); общие данные под
 * term_lock/term_unlock. */
#ifndef COMBO_TERM_H
#define COMBO_TERM_H

#include <stdint.h>

#define TK_UP    0xF8
#define TK_DOWN  0xF9
#define TK_RIGHT 0xFA
#define TK_LEFT  0xFB
#define TK_HOME  0xFC
#define TK_DEL   0xFD
#define TK_F1    0xFE           /* F1..F5 -- ESC O P .. ESC [ 1 5 ~ */
#define TK_FN    0xFF           /* + следующий байт 2..5: F2..F5 */

#define TERM_DIFF_MAX 240       /* разницы в одном ответе, байт: три строки 80 знаков --
                                 * строка приходит целиком, группами TERM.COM */

/* ЦВЕТА. На экране «Вектора» в 80 колонках четыре цвета (режим 512). Экран
 * ESP (vt.c) хранит 16 цветов ANSI, а term_io отдаёт ячейки уже с номерами
 * 0..3: в байте цвета разряды 1..0 -- буква, 3..2 -- фон. Какие это цвета,
 * подбирает palette.c под то, что на экране (CIEDE2000), раз в TERM_PAL_MS.
 * Новые цвета уходят машине командой 04 в начале разницы, и заново -- только
 * ячейки, у которых сменился номер. Ячейка 0 -- всегда чёрный ANSI 0. */
#define TERM_PAL_MS 300
void term_colors(uint8_t col[4]);       /* байты палитры «Вектора», BBGGGRRR */
void term_state(uint8_t col[4], uint8_t map[16]);   /* для проверок */

void term_init(void);
/* Начать сеанс: кодировка BBS (VT_CP437, VT_CP866, VT_UTF8). Экран у машины
 * чистый (TERM.COM очищает его сам), так что придёт только непустое. Модем не трогается: соединение переживает выход из
 * TERM.COM и повторный вход. */
void term_open(int charset);
/* Клавиши с машины, n байт; ответ -- разница экрана в out, не больше max. */
int  term_io(const uint8_t *keys, int n, uint8_t *out, int max);
/* Шаг модема и экрана. */
void term_pump(uint32_t now_ms);

/* Замок общих данных: на плате -- мьютекс FreeRTOS, на маке -- пусто. */
void term_lock(void);
void term_unlock(void);

/* Плата: замок, term_init и задача модема (term_esp.c). */
void term_start(void);

#endif
